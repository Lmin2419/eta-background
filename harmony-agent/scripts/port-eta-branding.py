import json
import re
from eta_port_common import arguments, emit

def generate(root, output, check=False):
    source=(root/'app/src/main/kotlin/io/github/mangi/eta/ui/components/ProviderBranding.kt').read_text()
    providers=re.findall(r'ProviderSourceTypes\.(\w+) -> R.drawable.(\w+)', source)
    rules=[]
    for logo, kind, args in re.findall(r'ModelBrandRule\(\s*(?:logo = )?R.drawable.(\w+),\s*(?:pattern = )?(modelFamilyPattern|Regex)\((.*?)\),?\s*\)',source,re.S):
        names=[json.loads(s) for s in re.findall(r'"(?:\\.|[^"\\])*"',args)]
        pattern='(?:^|[/_:.-])(?:'+'|'.join(names)+')(?:$|[/_:.-]|\\d)' if kind=='modelFamilyPattern' else names[0]
        rules.append((logo,pattern))
    if len(providers)!=12 or len(rules)!=18: raise ValueError('Brand source shape changed')
    header='// Ported from app/src/main/kotlin/io/github/mangi/eta/ui/components/ProviderBranding.kt @ 3b1794d.\n// Required Notice: Copyright © 2026 蛮吉 (Mangi-11).\n// Generated by scripts/port-eta-branding.py.\n'
    code=header+'export function modelBrandLogoRes(modelId: string): string | null {\n  const value=modelId.trim().toLowerCase();\n'
    for logo,pattern in rules: code+='  if(new RegExp('+json.dumps(pattern)+').test(value)) return '+json.dumps(logo)+';\n'
    code+='  return null;\n}\nexport function providerBrandLogoRes(sourceType: string): string | null {\n  switch(sourceType.trim().toLowerCase()) {\n'
    for kind,logo in providers: code+='    case '+json.dumps(kind.lower())+': return '+json.dumps(logo)+';\n'
    code+='    default: return null;\n  }\n}\nexport function modelOrProviderBrandLogoRes(model: string | null, provider: string | null): string | null { return (model ? modelBrandLogoRes(model) : null) ?? (provider ? providerBrandLogoRes(provider) : null); }\n'
    emit(output/'entry/src/main/ets/core/eta/providerBranding.ts',code,check)
    code=header+"import { modelOrProviderBrandLogoRes } from '../../../core/eta/providerBranding';\nexport function modelBrandResource(model: string, provider: string): Resource | null {\n  switch(modelOrProviderBrandLogoRes(model,provider)) {\n"
    for logo in sorted(set([p[1] for p in providers]+[r[0] for r in rules])): code+="    case '"+logo+"': return $r('app.media."+logo+"');\n"
    code+='    default: return null;\n  }\n}\n'
    emit(output/'entry/src/main/ets/ui/eta/components/ModelBrandResources.ets',code,check)

if __name__=='__main__':
    args=arguments(__doc__);generate(args.eta_root,args.output_root,args.check)
