#!/usr/bin/env python3
"""Convert the 胖小胖 brand SVG into the app's vector drawables.

Only supports what pangxiaopang.svg uses: path / ellipse / circle, solid or gradient fills,
strokes, opacity, and one rotate(angle cx cy) group. SVG gradients are objectBoundingBox;
VectorDrawable gradients are absolute, so each gradient's absolute geometry is listed below.

Usage (from the repo root): python3 etax/design/brand/svg2vector.py
"""
import pathlib
import re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "etax/design/brand/pangxiaopang.svg"
RES = ROOT / "app/src/main/res/drawable"
NS = {"s": "http://www.w3.org/2000/svg"}

# Absolute gradient geometry in the 512 art space (bbox of the shapes each gradient paints).
LINEAR = {
    "pxFur": (256, 150, 256, 446),
    "pxEar": (256, 122, 256, 216),
    "pxBib": (256, 372, 256, 490),
}


def color(value: str, alpha: float = 1.0) -> str:
    v = value.lstrip("#")
    if len(v) == 3:
        v = "".join(c * 2 for c in v)
    return f"#{round(alpha * 255):02X}{v.upper()}"


def gradients(root):
    out = {}
    for g in root.iter():
        tag = g.tag.split("}")[1]
        if tag not in ("linearGradient", "radialGradient"):
            continue
        stops = [(float(s.get("offset")), s.get("stop-color")) for s in g if s.tag.endswith("stop")]
        out[g.get("id")] = (tag, stops)
    return out


def ellipse_path(cx, cy, rx, ry):
    return (f"M{cx - rx:g},{cy:g} a{rx:g},{ry:g} 0 1,0 {2 * rx:g},0 "
            f"a{rx:g},{ry:g} 0 1,0 {-2 * rx:g},0 Z")


def element(el, grads, indent):
    tag = el.tag.split("}")[1]
    if tag == "path":
        d = el.get("d")
    elif tag == "ellipse":
        d = ellipse_path(*(float(el.get(k)) for k in ("cx", "cy", "rx", "ry")))
    elif tag == "circle":
        r = float(el.get("r"))
        d = ellipse_path(float(el.get("cx")), float(el.get("cy")), r, r)
    else:
        return ""
    opacity = float(el.get("opacity", "1"))
    attrs = [f'android:pathData="{d}"']
    gradient_xml = ""
    fill = el.get("fill", "#000000")
    if fill.startswith("url("):
        gid = re.search(r"#([^)]+)", fill).group(1)
        kind, stops = grads[gid]
        items = "".join(f'\n{indent}            <item android:offset="{o:g}" android:color="{color(c)}" />' for o, c in stops)
        if kind == "linearGradient":
            x1, y1, x2, y2 = LINEAR[gid]
            geometry = (f'android:type="linear" android:startX="{x1}" android:startY="{y1}" '
                        f'android:endX="{x2}" android:endY="{y2}"')
        else:  # radial on an ellipse: centre at (cx, cy - 0.1 ry), radius 1.2 x mean radius (cx .5 cy .45 r .6).
            cx, cy, rx, ry = (float(el.get(k)) for k in ("cx", "cy", "rx", "ry"))
            geometry = (f'android:type="radial" android:centerX="{cx:g}" android:centerY="{cy - 0.1 * ry:g}" '
                        f'android:gradientRadius="{1.2 * (rx + ry) / 2:g}"')
        gradient_xml = (f'\n{indent}    <aapt:attr name="android:fillColor">\n{indent}        <gradient {geometry}>'
                        f'{items}\n{indent}        </gradient>\n{indent}    </aapt:attr>')
    elif fill != "none":
        attrs.append(f'android:fillColor="{color(fill)}"')
        if opacity < 1:
            attrs.append(f'android:fillAlpha="{opacity:g}"')
    stroke = el.get("stroke")
    if stroke and stroke != "none":
        attrs.append(f'android:strokeColor="{color(stroke)}"')
        attrs.append(f'android:strokeWidth="{el.get("stroke-width", "1")}"')
        if opacity < 1:
            attrs.append(f'android:strokeAlpha="{opacity:g}"')
        if el.get("stroke-linecap"):
            attrs.append(f'android:strokeLineCap="{el.get("stroke-linecap")}"')
        if el.get("stroke-linejoin"):
            attrs.append(f'android:strokeLineJoin="{el.get("stroke-linejoin")}"')
    joined = f"\n{indent}    ".join(attrs)
    if gradient_xml:
        return f"{indent}<path\n{indent}    {joined}>{gradient_xml}\n{indent}</path>\n"
    return f"{indent}<path\n{indent}    {joined} />\n"


def art(indent):
    root = ET.parse(SRC).getroot()
    grads = gradients(root)
    group = root.find("s:g", NS)
    angle, px, py = (float(v) for v in re.findall(r"[-\d.]+", group.get("transform")))
    body = "".join(element(el, grads, indent + "    ") for el in group)
    return (f'{indent}<group android:rotation="{angle:g}" android:pivotX="{px:g}" android:pivotY="{py:g}">\n'
            f"{body}{indent}</group>\n")


HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          "<!-- Generated by etax/design/brand/svg2vector.py from pangxiaopang.svg. Edit the SVG, then re-run. -->\n")


def write(name, width, viewport, inner):
    (RES / name).write_text(
        HEADER
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        + '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        + f'    android:width="{width}dp"\n    android:height="{width}dp"\n'
        + f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
        + inner + "</vector>\n")


# Launcher foreground: the 512 art fills the visible 72dp window of the 108dp layer.
write("ic_launcher_foreground.xml", 108, 108,
      '    <group android:scaleX="0.140625" android:scaleY="0.140625" android:translateX="18" android:translateY="18">\n'
      + art("        ") + "    </group>\n")
# In-app brand mark (empty state, assistant avatar): the art itself, no ground.
write("ic_eta_mark.xml", 48, 512, art("    "))
print("wrote ic_launcher_foreground.xml, ic_eta_mark.xml")
